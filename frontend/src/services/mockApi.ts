import { AGENT_NAMES } from '../data/agents';
import type { AgentId, AgentRun, RunStep, Source } from '../types';

/**
 * This module is the seam between the UI and the real Python backend.
 * `streamRun` has the same shape an SSE-backed implementation would have, so
 * swapping in a real `fetch` + ReadableStream client does not change any UI code.
 */

export interface StreamOptions {
  delayMs?: number;
  signal?: AbortSignal;
}

export type RunEvent =
  | { type: 'start'; run: AgentRun }
  | { type: 'step'; runId: string; step: RunStep }
  | { type: 'complete'; runId: string; answer: string; sources: Source[] }
  | { type: 'error'; runId: string; message: string };

const DATA_KEYWORDS =
  /\b(document|documents|pdf|policy|policies|database|qdrant|rag|internal|report|reports|contract|handbook|knowledge)\b/i;
const WEB_KEYWORDS =
  /\b(latest|news|current|currently|today|recent|recently|web|internet|search|outside|market|competitor|update)\b/i;

const STEP_DETAILS: Record<
  AgentId,
  { action: string; detail: string; durationMs: number }
> = {
  router: {
    action: 'Classifying intent',
    detail: 'Matched the request against agent capabilities and selected a route.',
    durationMs: 210,
  },
  'data-sources': {
    action: 'Retrieving context',
    detail: 'MCP RAG tool searched Qdrant collections and returned 3 grounded passages.',
    durationMs: 480,
  },
  'internet-search': {
    action: 'Searching the web',
    detail: 'Fetched 5 fresh results and ranked them by relevance and recency.',
    durationMs: 640,
  },
};

let idCounter = 0;

function makeId(prefix: string): string {
  idCounter += 1;
  return `${prefix}-${Date.now().toString(36)}-${idCounter}`;
}

function wait(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal?.aborted) {
      reject(new DOMException('Aborted', 'AbortError'));
      return;
    }

    const onAbort = () => {
      clearTimeout(timer);
      signal?.removeEventListener('abort', onAbort);
      reject(new DOMException('Aborted', 'AbortError'));
    };
    const timer = setTimeout(() => {
      signal?.removeEventListener('abort', onAbort);
      resolve();
    }, ms);

    signal?.addEventListener('abort', onAbort);
  });
}

/** Pure routing rule: which agents should handle this query? */
export function chooseRoute(query: string): AgentId[] {
  const wantsData = DATA_KEYWORDS.test(query);
  const wantsWeb = WEB_KEYWORDS.test(query);

  if (wantsData && wantsWeb) {
    return ['router', 'data-sources', 'internet-search'];
  }
  if (wantsData) {
    return ['router', 'data-sources'];
  }
  if (wantsWeb) {
    return ['router', 'internet-search'];
  }
  // Ambiguous requests fan out to both specialists for maximum recall.
  return ['router', 'data-sources', 'internet-search'];
}

function buildSources(route: AgentId[]): Source[] {
  const sources: Source[] = [];
  if (route.includes('data-sources')) {
    sources.push({
      title: 'Internal handbook · Qdrant collection "policies"',
      url: 'qdrant://collections/policies',
      kind: 'vector-db',
    });
    sources.push({
      title: 'Vendor contract archive · Qdrant collection "contracts"',
      url: 'qdrant://collections/contracts',
      kind: 'vector-db',
    });
  }
  if (route.includes('internet-search')) {
    sources.push({
      title: 'Oracle AI Agent Studio — documentation',
      url: 'https://www.oracle.com/artificial-intelligence/ai-agents/',
      kind: 'web',
    });
    sources.push({
      title: 'Model Context Protocol — specification',
      url: 'https://modelcontextprotocol.io/',
      kind: 'web',
    });
  }
  return sources;
}

function buildAnswer(query: string, route: AgentId[]): string {
  const specialists = route.filter((id) => id !== 'router').map((id) => AGENT_NAMES[id]);
  const shortQuery = query.length > 90 ? `${query.slice(0, 87)}...` : query;
  const path = specialists.length > 0 ? specialists.join(' + ') : 'Router only';

  return `I routed "${shortQuery}" through the Router Agent (${path}). The selected agents completed their work and their outputs were merged into this answer. In the production system this text is generated by the Bedrock-backed router from the retrieved passages and web results listed below.`;
}

/** Simulates the backend's event stream. One event per orchestration phase. */
export async function* streamRun(
  query: string,
  options: StreamOptions = {},
): AsyncGenerator<RunEvent> {
  const { delayMs = 320, signal } = options;
  const trimmed = query.trim();
  const runId = makeId('run');

  if (!trimmed) {
    yield { type: 'error', runId, message: 'Enter a question before running the agents.' };
    return;
  }

  const route = chooseRoute(trimmed);
  const initialRun: AgentRun = {
    id: runId,
    query: trimmed,
    route,
    status: 'running',
    createdAt: new Date().toISOString(),
    steps: [],
    answer: '',
    sources: [],
  };
  yield { type: 'start', run: { ...initialRun } };

  try {
    for (const agentId of route) {
      await wait(delayMs, signal);
      const detail = STEP_DETAILS[agentId];
      yield {
        type: 'step',
        runId,
        step: {
          id: makeId('step'),
          agent: agentId,
          action: detail.action,
          detail: detail.detail,
          durationMs: detail.durationMs,
          status: 'ok',
        },
      };
    }

    await wait(Math.min(delayMs, 180), signal);
    yield {
      type: 'complete',
      runId,
      answer: buildAnswer(trimmed, route),
      sources: buildSources(route),
    };
  } catch (error) {
    if (signal?.aborted) {
      return;
    }
    yield {
      type: 'error',
      runId,
      message: error instanceof Error ? error.message : 'Unexpected orchestration error.',
    };
  }
}

